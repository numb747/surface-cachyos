-- ============================================================================
--  平板模式手势集（纯触摸，不依赖物理键盘）
--
--  由 config/touch.lua 在【配置加载时】按标记文件条件 require：
--      ~/.local/state/surface-config/tablet.flag 存在 → 加载本文件
--  开关用 ~/.local/bin/tablet-mode {on|off|toggle|status}
--
--  ■ 指头数分配（与 touch.lua 【不能重复】）
--     本文件只用：2 指长按（救援）、5 指长按（退出平板模式）
--     touch.lua 用：3/4/5 指点击、3/4 指长按
--
--  ■ 本文件的重做原则（2026-09-26）
--    原版是按 PC 习惯写的，很多手势在平板上【误触代价过大】。实测这台机器的
--    触摸在快速移动时会断触（见 touch.lua 顶部说明），一次滑动可能被识别成
--    多次落指，于是：
--      · 四指滑动 → 切工作区：动画卡在半截，画面偏移且不复位
--      · 五指下滑 → 切抽屉工作区：空工作区盖住屏幕，看着像"窗口凭空消失"
--      · 三指滑动 → 把窗口丢到别的工作区：窗口"不见了"，纯触摸难找回
--    所以本版【滑动类手势全部移除】，切工作区/找窗口改走启动器。
--
--  ■ 与 inputs.lua 的原生手势会不会撞车？不会。
--     hyprgrass 监听 ITouch（触屏），原生 hl.gesture 监听
--     ITrackpadGesture（触控板），两个独立事件源。
-- ============================================================================

-- ── 0. 模式标识：橙色窗口边框 ─────────────────────────────────────────────
--
--    顶栏做不了随模式变化的图标（noctalia v5 的 custom_button 图标/文字是静态的，
--    动态标签是 v4 的功能，v5 没有；见 noctalia issue #4570）。
--    边框写在这里而不是另起一套判断：本文件【只在】平板模式下加载，所以边框
--    颜色和手势集来自同一个开关，不可能对不上。回 PC 模式 reload 时
--    decorations.lua 的默认绿色边框自然恢复。
--    ★ 放在 hyprgrass 检查之前：插件没加载时手势没了，但模式标识照样要有。
hl.config({
    general = {
        border_size = 3,
        col = {
            active_border = {
                colors = { "rgba(ffa94dff)", "rgba(f76707ff)" },
                angle = 45,
            },
        },
    },
})

if hl.plugin.hyprgrass == nil then
    return
end

-- ── A. 救援手势（误触之后的救命键）────────────────────────────────────────

-- A1 双指长按 → 复位界面
--
--    ★ 这是本文件最重要的一条。原版没有兜底，一旦手势误触把界面切到
--      空工作区、或卡在半截滑动里，纯触摸用户【没有任何办法回来】——
--      平板模式下没有键盘，够不着 SUPER+1。
--      有了这条，最坏情况也只要两根手指按住 0.5 秒。
--
--    脚本做的事：切回工作区 1、关掉抽屉工作区、把卡住的滑动偏移复位。
--    用 /usr/local/bin 的路径而非 ~/.local/bin，理由同 touch.lua 里那段说明。
hl.plugin.hyprgrass.bind {
    pattern = { kind = "longpress", fingers = 2 },
    action  = hl.dsp.exec_cmd("/usr/local/bin/tablet-rescue"),
}

-- ── B. 系统控制 ────────────────────────────────────────────────────────────

-- B1 五指长按 → 手动切回 PC 模式
--
--    udev 自动检测失灵时（外接 USB 键盘误判、休眠恢复后状态错乱）的最后退路。
--    用长按而不是点击：切模式是不可逆动作，需要比"点一下"更明确的意图。
hl.plugin.hyprgrass.bind {
    pattern = { kind = "longpress", fingers = 5 },
    action  = hl.dsp.exec_cmd("/usr/local/bin/tablet-mode off"),
}
